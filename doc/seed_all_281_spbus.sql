-- 3. STORED PROCEDURE ATOMIK SELF-HEALING: submit_spbu_report
-- Hapus versi lama yang overloaded agar tidak ambigu (ERROR 42725)
DROP FUNCTION IF EXISTS public.submit_spbu_report(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT);
DROP FUNCTION IF EXISTS public.submit_spbu_report(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT);

CREATE OR REPLACE FUNCTION public.submit_spbu_report(
    p_spbu_id TEXT,
    p_queue_level TEXT,
    p_pertalite TEXT,
    p_pertamax TEXT,
    p_solar TEXT,
    p_note TEXT DEFAULT NULL,
    p_ip_hash TEXT DEFAULT NULL,
    p_spbu_name TEXT DEFAULT NULL,
    p_regency TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_wait_minutes INT;
    v_result JSONB;
BEGIN
    -- Estimasi menit antrean
    v_wait_minutes := CASE 
        WHEN p_queue_level = 'empty' THEN 0
        WHEN p_queue_level = 'smooth' THEN 5
        WHEN p_queue_level = 'moderate' THEN 20
        WHEN p_queue_level = 'congested' THEN 45
        ELSE 10
    END;

    -- Self-Healing: Jika SPBU belum ada di database, buat baris dasar terlebih dahulu
    IF NOT EXISTS (SELECT 1 FROM public.spbus WHERE id = p_spbu_id) THEN
        INSERT INTO public.spbus (
            id, code, name, address, regency, district, lat, lng, queue_level, estimated_wait_minutes, fuel_stock, cctv, report_count, upvotes, last_reported_at
        ) VALUES (
            p_spbu_id, 
            'SPBU', 
            COALESCE(p_spbu_name, 'SPBU Pertamina'), 
            'Bali', 
            COALESCE(p_regency, 'Denpasar'), 
            'Bali', 
            -8.65, 
            115.21, 
            p_queue_level, 
            v_wait_minutes, 
            jsonb_build_object('pertalite', p_pertalite, 'pertamax', p_pertamax, 'solar', p_solar), 
            '{"hasCCTV": false}'::jsonb, 
            0, 
            0, 
            NOW()
        );
    END IF;

    -- 1. Catat ke riwayat laporan warga
    INSERT INTO public.spbu_reports (
        spbu_id, queue_level, pertalite, pertamax, solar, note, ip_hash, created_at
    ) VALUES (
        p_spbu_id, p_queue_level, p_pertalite, p_pertamax, p_solar, p_note, p_ip_hash, NOW()
    );

    -- 2. Update status SPBU master
    UPDATE public.spbus
    SET 
        queue_level = p_queue_level,
        estimated_wait_minutes = v_wait_minutes,
        fuel_stock = jsonb_set(
            jsonb_set(
                jsonb_set(fuel_stock, '{pertalite}', to_jsonb(p_pertalite)),
                '{pertamax}', to_jsonb(p_pertamax)
            ),
            '{solar}', to_jsonb(p_solar)
        ),
        report_count = report_count + 1,
        last_reported_at = NOW(),
        updated_at = NOW()
    WHERE id = p_spbu_id;

    -- Ambil data spbu terupdate
    SELECT to_jsonb(s) INTO v_result FROM public.spbus s WHERE s.id = p_spbu_id;
    RETURN v_result;
END;
$$;

GRANT EXECUTE ON FUNCTION public.submit_spbu_report(TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT) TO anon, authenticated;

